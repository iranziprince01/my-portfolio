import { put } from '@vercel/blob'
import { readdir, readFile, writeFile, access } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, '..')
const publicDir = path.join(root, 'public')
const mediaDir = path.join(root, 'media')

const IMAGE_EXT = new Set(['.jpg', '.jpeg', '.png', '.webp', '.gif', '.avif'])

async function loadEnvLocal() {
  try {
    const raw = await readFile(path.join(root, '.env.local'), 'utf8')
    for (const line of raw.split('\n')) {
      const trimmed = line.trim()
      if (!trimmed || trimmed.startsWith('#')) continue
      const eq = trimmed.indexOf('=')
      if (eq === -1) continue
      const key = trimmed.slice(0, eq)
      let value = trimmed.slice(eq + 1)
      if (
        (value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'"))
      ) {
        value = value.slice(1, -1)
      }
      if (!process.env[key]) process.env[key] = value
    }
  } catch {
    // ignore missing .env.local
  }
}

async function exists(dir) {
  try {
    await access(dir)
    return true
  } catch {
    return false
  }
}

await loadEnvLocal()

if (!process.env.BLOB_READ_WRITE_TOKEN) {
  console.error('Missing BLOB_READ_WRITE_TOKEN. Run: vercel env pull .env.local --yes')
  process.exit(1)
}

/** Prefer ./media (source of truth after migration), fall back to ./public */
const sourceDirs = []
if (await exists(mediaDir)) sourceDirs.push(mediaDir)
if (await exists(publicDir)) sourceDirs.push(publicDir)

/** @type {Map<string, string>} */
const filesByName = new Map()
for (const dir of sourceDirs) {
  const entries = await readdir(dir, { withFileTypes: true })
  for (const entry of entries) {
    if (!entry.isFile()) continue
    if (!IMAGE_EXT.has(path.extname(entry.name).toLowerCase())) continue
    if (!filesByName.has(entry.name)) {
      filesByName.set(entry.name, path.join(dir, entry.name))
    }
  }
}

const files = [...filesByName.keys()].sort((a, b) => a.localeCompare(b))
if (!files.length) {
  console.error('No images found in ./media or ./public')
  process.exit(1)
}

/** @type {Record<string, string>} */
const media = {}

for (const name of files) {
  const localPath = filesByName.get(name)
  const pathname = `portfolio/${name}`
  const buffer = await readFile(localPath)
  const blob = await put(pathname, buffer, {
    access: 'public',
    addRandomSuffix: false,
    allowOverwrite: true,
    cacheControlMaxAge: 60 * 60 * 24 * 365,
  })
  media[`/${name}`] = blob.url
  console.log(`Uploaded ${name} -> ${blob.url}`)
}

const host = Object.values(media)[0]
  ? new URL(Object.values(media)[0]).host
  : 'e8zjl9cczfol7u0a.public.blob.vercel-storage.com'

const fileContents = `/**
 * Public CDN URLs for portfolio media stored in Vercel Blob.
 * Regenerated by: npm run media:upload
 */
export const BLOB_HOST = ${JSON.stringify(host)} as const

export const media = ${JSON.stringify(media, null, 2)} as const

export type MediaPath = keyof typeof media
`

await writeFile(path.join(root, 'src/data/media-urls.ts'), fileContents)
console.log(`\nWrote src/data/media-urls.ts (${files.length} images)`)
console.log(`Blob host: ${host}`)
